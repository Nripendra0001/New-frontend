class ExamEngine {
    constructor() {
        this.questions = [];
        this.currentQuestions = [];
        this.currentIndex = 0;
        this.userAnswers = {};
        this.visited = new Set([0]);
        this.timer = null;
        this.timeLeft = 0;
        this.exam = '';
        this.mode = 'full';
        this.language = 'en';

        this.init();
    }

    async init() {
        const urlParams = new URLSearchParams(window.location.search);
        this.exam = urlParams.get('exam') || 'ssc_gd';
        this.mode = urlParams.get('mode') || 'full';
        
        this.loadQuestions();
        this.setupEventListeners();
        this.renderInitialUI();
        this.startTimer();
        this.renderQuestion();
    }

    loadQuestions() {
        // Fix: Replace underscores with hyphens to match keys in question.js
        const legacyKey = this.exam.replace(/_/g, '-');
        const legacyData = QUESTION_BANK[legacyKey] || [];
        const generatedData = this.getGeneratedQuestionsByExam(this.exam);
        const data = [...legacyData, ...generatedData].map((q) => this.normalizeQuestion(q));
        const targetCount = this.mode === 'practice' ? 20 : 50;
        this.currentQuestions = this.shuffle(data).slice(0, targetCount);
        this.timeLeft = (this.mode === 'practice' ? 20 : 60) * 60;
    }

    getGeneratedQuestionsByExam(examKey) {
        // Fix: normalize examKey to use underscores for mapping
        const normalizedKey = String(examKey || "").toLowerCase().replace(/-/g, '_');
        const examNameMap = {
            ssc_gd: "SSC GD",
            ssc_cgl: "SSC CGL",
            ssc_chsl: "SSC CHSL",
            railway_ntpc: "Railway NTPC",
            up_police: "UP Police",
            delhi_police: "Delhi Police",
            upsssc: "UPSSSC",
            army_gd: "Army GD"
        };
        const examName = examNameMap[normalizedKey];
        if (!examName) return [];
        const generatedData = [
            ...GENERATED_QUESTION_BANK_901_1000,
            ...GENERATED_QUESTION_BANK_1101_1200,
            ...GENERATED_QUESTION_BANK_1201_1500,
            ...GENERATED_QUESTION_BANK_1501_2500,
            ...GENERATED_QUESTION_BANK_2501_3000
        ];
        return generatedData.filter((q) => q.exam === examName);
    }

    normalizeQuestion(q) {
        if (!q) return null;
        const options = Array.isArray(q.options) ? q.options : [];
        const rawAns = q.answer !== undefined ? q.answer : q.ans;
        
        let answerIndex = -1;
        if (typeof rawAns === 'number') {
            answerIndex = rawAns;
        } else if (typeof rawAns === 'string') {
            answerIndex = options.findIndex(opt => String(opt).trim() === rawAns.trim());
        }

        return {
            ...q,
            question_hi: q.question_hi || q.q || q.question,
            options_hi: Array.isArray(q.options_hi) ? q.options_hi : options,
            answer: answerIndex >= 0 ? answerIndex : 0,
            subject: q.subject || "MISC"
        };
    }

    shuffle(array) {
        return array.sort(() => Math.random() - 0.5);
    }

    setupEventListeners() {
        document.getElementById('saveNextBtn')?.addEventListener('click', () => this.saveAndNext());
        document.getElementById('prevBtn')?.addEventListener('click', () => this.prevQuestion());
        document.getElementById('markBtn')?.addEventListener('click', () => this.markForReview());
        document.getElementById('clearBtn')?.addEventListener('click', () => this.clearResponse());
        document.getElementById('submitBtn')?.addEventListener('click', () => this.confirmSubmit());
        document.getElementById('submitBtnTop')?.addEventListener('click', () => this.confirmSubmit());
    }

    setLanguage(lang) {
        this.language = lang;
        document.getElementById('btn-en')?.classList.toggle('active', lang === 'en');
        document.getElementById('btn-hi')?.classList.toggle('active', lang === 'hi');
        this.renderQuestion();
    }

    startTimer() {
        const timerDisplay = document.getElementById('timer');
        this.timer = setInterval(() => {
            if (this.timeLeft <= 0) { this.submitTest(); return; }
            this.timeLeft--;
            const hrs = Math.floor(this.timeLeft / 3600);
            const mins = Math.floor((this.timeLeft % 3600) / 60);
            const secs = this.timeLeft % 60;
            if (timerDisplay) timerDisplay.textContent = `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
        }, 1000);
    }

    renderQuestion() {
        const q = this.currentQuestions[this.currentIndex];
        if (!q) return;

        const questionText = this.language === 'hi' ? q.question_hi : q.question;
        const optionsList = this.language === 'hi' ? (q.options_hi || q.options) : q.options;

        document.getElementById('qNo').textContent = `Question ${this.currentIndex + 1}`;
        document.getElementById('qTopic').textContent = `Topic: ${q.subject}`;
        document.getElementById('qText').innerHTML = questionText;

        const optionsBox = document.getElementById('optionsBox');
        optionsBox.innerHTML = optionsList.map((opt, i) => `
            <label class="opt" onclick="engine.selectOption(${i})">
                <input type="radio" name="qOption" ${this.userAnswers[this.currentIndex]?.answer === i ? 'checked' : ''}>
                <span>${opt}</span>
            </label>
        `).join('');

        this.updatePalette();
        this.updateStats();
    }

    selectOption(index) {
        if (!this.userAnswers[this.currentIndex]) this.userAnswers[this.currentIndex] = {};
        this.userAnswers[this.currentIndex].answer = index;
    }

    saveAndNext() {
        if (this.userAnswers[this.currentIndex]?.answer !== undefined) this.userAnswers[this.currentIndex].status = 'answered';
        this.nextQuestion();
    }

    markForReview() {
        if (!this.userAnswers[this.currentIndex]) this.userAnswers[this.currentIndex] = {};
        this.userAnswers[this.currentIndex].status = 'review';
        this.nextQuestion();
    }

    clearResponse() { delete this.userAnswers[this.currentIndex]; this.renderQuestion(); }

    nextQuestion() { if (this.currentIndex < this.currentQuestions.length - 1) { this.currentIndex++; this.visited.add(this.currentIndex); this.renderQuestion(); } }
    prevQuestion() { if (this.currentIndex > 0) { this.currentIndex--; this.visited.add(this.currentIndex); this.renderQuestion(); } }
    jumpToQuestion(index) { this.currentIndex = index; this.visited.add(this.currentIndex); this.renderQuestion(); }

    updatePalette() {
        const palette = document.getElementById('palette');
        palette.innerHTML = this.currentQuestions.map((_, i) => {
            const status = this.userAnswers[i]?.status;
            let stateClass = status === 'answered' ? 'answered' : (status === 'review' ? 'review' : (this.visited.has(i) ? 'skipped' : 'notVisited'));
            if (this.currentIndex === i) stateClass += ' active';
            return `<button class="qBtn ${stateClass}" onclick="engine.jumpToQuestion(${i})">${i + 1}</button>`;
        }).join('');
    }

    updateStats() {
        let answered = 0, review = 0, skipped = 0;
        this.currentQuestions.forEach((_, i) => {
            const status = this.userAnswers[i]?.status;
            if (status === 'answered') answered++; else if (status === 'review') review++; else if (this.visited.has(i)) skipped++;
        });
        document.getElementById('stTotal').textContent = this.currentQuestions.length;
        document.getElementById('stAnswered').textContent = answered;
        document.getElementById('stReview').textContent = review;
        document.getElementById('stNotAnswered').textContent = skipped;
    }

    renderInitialUI() {
        const examNameMap = {
            ssc_gd: "SSC GD",
            ssc_cgl: "SSC CGL",
            ssc_chsl: "SSC CHSL",
            railway_ntpc: "Railway NTPC",
            up_police: "UP Police",
            delhi_police: "Delhi Police",
            upsssc: "UPSSSC",
            army_gd: "Army GD"
        };
        const mappedName = examNameMap[this.exam] || this.exam.toUpperCase().replace(/_/g, ' ');
        document.getElementById('examTitle').textContent = `${mappedName} ${this.mode.toUpperCase()}`;
        const student = JSON.parse(localStorage.getItem('studentDetails') || '{}');
        document.getElementById('candidateName').textContent = student.name || 'Candidate';
        document.getElementById('examMeta').textContent = `${this.currentQuestions.length} Questions | ${this.mode === 'practice' ? 20 : 60} Min`;
    }

    confirmSubmit() { if (confirm("Submit Test?")) this.submitTest(); }

    submitTest() {
        clearInterval(this.timer);
        const results = this.calculateResults();
        localStorage.setItem('lastTestResult', JSON.stringify(results));
        window.location.href = `predicy-result.html`;
    }

    calculateResults() {
        let correct = 0, incorrect = 0, attempted = 0;
        const questionsHistory = [];
        const topicStats = {};

        this.currentQuestions.forEach((q, i) => {
            const userAns = this.userAnswers[i];
            const topic = q.subject;
            if (!topicStats[topic]) topicStats[topic] = { total: 0, attempted: 0, correct: 0 };
            topicStats[topic].total++;
            let status = 'skipped', selected = null;

            if (userAns?.answer !== undefined) {
                attempted++; topicStats[topic].attempted++; selected = userAns.answer;
                if (userAns.answer === q.answer) { correct++; topicStats[topic].correct++; status = 'correct'; }
                else { incorrect++; status = 'wrong'; }
            }

            questionsHistory.push({ q: q.question, options: q.options, ans: q.answer, selected: selected, topic: topic, status: status });
        });

        const totalTime = (this.mode === 'practice' ? 20 : 60) * 60;
        return {
            exam: this.exam, 
            mode: this.mode, 
            totalQuestions: this.currentQuestions.length,
            attempted, 
            correct, 
            wrong: incorrect, 
            unattempted: this.currentQuestions.length - attempted,
            score: (correct * 4) - (incorrect * 1), // Synced with predict-result.js
            accuracy: attempted > 0 ? (correct / attempted) * 100 : 0,
            timeTakenSec: totalTime - this.timeLeft, 
            questions: questionsHistory, 
            topicStats: topicStats
        };
    }
}

const engine = new ExamEngine();
